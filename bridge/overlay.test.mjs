import {test} from 'node:test';
import assert from 'node:assert/strict';
import {normalize} from './normalize.mjs';
import {Sessions} from './sessions.mjs';
import {createServer} from './server.mjs';
const token='a'.repeat(32),other='b'.repeat(32),readToken='r'.repeat(40);
const viewA='1'.repeat(64),viewB='2'.repeat(64);
const adapter=()=>({connect:async()=>{},close(){}});
test('profile contains only real display metadata and validates avatar URL',()=>{
  const event=normalize('comment',{user:{displayId:'viewer',nickname:'คนบ้านMinecraft2001',followInfo:{followingCount:'210',followerCount:43},avatarThumb:{urlList:['https://p16-common-sign.tiktokcdn.com/avatar']}},common:{msgId:'1'}});
  assert.equal(event.profile.nickname,'คนบ้านMinecraft2001');
  assert.equal(event.profile.following,210);assert.equal(event.profile.followers,43);
  assert.ok(event.profile.avatarUrl.startsWith('https://'));
  const missing=normalize('follow',{user:{displayId:'a',avatarThumb:{urlList:['https://evil.example/a']}}});
  assert.equal(missing.profile.followers,null);assert.equal(missing.profile.avatarUrl,null);
});
test('overlay follows displayed event, not newest ingest; revision and sessions remain isolated',()=>{
  const s=new Sessions(adapter);s.connect(token,'channel',viewA);s.connect(other,'channel',viewB);
  const e=normalize('comment',{user:{displayId:'first'},msgId:'1'});
  s.push(s.items.get(token),e);s.push(s.items.get(token),normalize('comment',{user:{displayId:'next'},msgId:'2'}));
  assert.equal(s.overlay(viewA),null);
  assert.equal(s.setOverlay(token,e.id,2),true);assert.equal(s.overlay(viewA).profile.handle,'first');
  assert.equal(s.setOverlay(token,'comment:2',1),false);
  assert.equal(s.setOverlay(other,e.id,1),false);assert.equal(s.overlay(viewB),null);
  s.push(s.items.get(other),normalize('comment',{user:{displayId:'second'},msgId:'3'}));s.setOverlay(other,'comment:3',1);
  assert.equal(s.overlay(viewB).profile.handle,'second');assert.equal(s.overlay(viewA).profile.handle,'first');
  s.disconnect(token);assert.equal(s.overlay(viewA),null);assert.equal(s.overlay(viewB).profile.handle,'second');s.close();
});
test('overlay read token cannot connect or mutate; current updates require session auth',async t=>{
  const s=new Sessions(adapter),key='secret'.repeat(6);
  const server=createServer({key,sessions:s,overlaySigningKey:readToken});await new Promise(r=>server.listen(0,'127.0.0.1',r));
  t.after(()=>{s.close();server.closeAllConnections();server.close();});
  const base=`http://127.0.0.1:${server.address().port}`,headers={'X-Fame-Key':key,'X-Fame-Session':token};
  assert.equal((await fetch(base+'/overlay')).status,200);
  assert.equal((await fetch(base+'/overlay/state?channel=channel')).status,401);
  const connection=await(await fetch(base+'/connect',{method:'POST',headers,body:JSON.stringify({username:'channel',ownerId:123})})).json();
  assert.match(connection.overlayPath,/^\/overlay\?view=[a-f0-9]{64}$/);
  const view=new URL(connection.overlayPath,'http://localhost').searchParams.get('view');
  const state=()=>fetch(base+`/overlay/state?view=${view}`);
  assert.equal((await state()).status,200);
  s.push(s.items.get(token),normalize('comment',{user:{displayId:'viewer'},msgId:'1'}));
  assert.equal((await fetch(base+'/overlay/current',{method:'POST',headers:{'X-Fame-Key':view},body:'{}'})).status,401);
  const update=await fetch(base+'/overlay/current',{method:'POST',headers,body:JSON.stringify({id:'comment:1',revision:1})});assert.equal(update.status,200);
  const body=await(await state()).json();assert.equal(body.current.profile.handle,'viewer');
  assert.equal(JSON.stringify(body).includes(token),false);
  assert.equal((await fetch(base+'/overlay/current',{method:'POST',headers,body:JSON.stringify({id:'forged',revision:2})})).status,409);
  assert.equal((await fetch(base+`/overlay/state?channel=channel&token=${readToken}`)).status,401);
  assert.equal((await fetch(base+'/connect',{method:'POST',headers:{...headers,'X-Fame-Session':other},body:JSON.stringify({username:'channel',ownerId:'not-a-user'})})).status,400);
  const newHeaders={...headers,'X-Fame-Session':other};
  const next=await(await fetch(base+'/connect',{method:'POST',headers:newHeaders,body:JSON.stringify({username:'different',ownerId:123})})).json();
  assert.equal(next.overlayPath,connection.overlayPath);assert.equal(s.items.has(token),false);
  assert.equal((await(await state()).json()).current,null);
  const third=await(await fetch(base+'/connect',{method:'POST',headers:{...headers,'X-Fame-Session':'c'.repeat(32)},body:JSON.stringify({username:'different',ownerId:456})})).json();
  assert.notEqual(third.overlayPath,next.overlayPath);
});
test('personal overlay links are ready before Connect and never open a TikTok session',async t=>{
  let dialed=0;
  const s=new Sessions(()=>{dialed++;return adapter();});
  const key='secret'.repeat(6),server=createServer({key,sessions:s,overlaySigningKey:readToken});
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  t.after(()=>{s.close();server.closeAllConnections();server.close();});
  const base=`http://127.0.0.1:${server.address().port}`,headers={'X-Fame-Key':key,'X-Fame-Session':token};
  const link=async ownerId=>fetch(base+'/overlay/link',{method:'POST',headers,body:JSON.stringify({ownerId})});
  assert.equal((await link()).status,400);
  const response=await link(123);assert.equal(response.status,200);
  const first=await response.json(),second=await(await link(123)).json(),otherOwner=await(await link(456)).json();
  assert.equal(first.overlayPath,second.overlayPath);assert.notEqual(first.overlayPath,otherOwner.overlayPath);
  assert.match(first.activityPath,/^\/overlay\/activity\?view=[a-f0-9]{64}$/);
  await new Promise(r=>setImmediate(r));assert.equal(dialed,0);assert.equal(s.items.size,0);
  const view=new URL(first.overlayPath,base).searchParams.get('view');
  const idle=await(await fetch(base+'/overlay/state?view='+view)).json();
  assert.equal(idle.status,'DISCONNECTED');assert.equal(idle.current,null);assert.equal(idle.counts.rose,0);
  assert.equal((await fetch(base+first.activityPath)).status,200);
  for(const gift of ['rose','necklace','donut','heart']) {
    const image=await fetch(base+'/overlay/assets/'+gift+'.webp');
    assert.equal(image.status,200);assert.equal(image.headers.get('content-type'),'image/webp');
    const bytes=Buffer.from(await image.arrayBuffer());assert.equal(bytes.toString('ascii',8,12),'WEBP');
  }
  assert.equal((await fetch(base+'/overlay/assets/unknown.webp')).status,401);
  assert.equal('photoTest' in idle,false);
  const connected=await(await fetch(base+'/connect',{method:'POST',headers,body:JSON.stringify({username:'channel',ownerId:123})})).json();
  assert.equal(connected.overlayPath,first.overlayPath);
});
test('activity counts deduplicate received events and stay scoped to their owner',()=>{
  const s=new Sessions(adapter);s.connect(token,'channel',viewA);s.connect(other,'channel',viewB);
  const a=s.items.get(token);
  s.recordActivity(a,{id:'comment:one',kind:'comment'});
  s.push(a,{id:'rose:one',kind:'rose'});s.push(a,{id:'rose:one',kind:'rose'});
  s.recordActivity(a,{id:'like:one',kind:'like',count:8});s.recordActivity(a,{id:'like:one',kind:'like',count:8});
  assert.equal(s.overlayState(viewA).counts.comment,1);assert.equal(s.overlayState(viewA).counts.rose,1);
  assert.equal(s.overlayState(viewA).counts.necklace,0);assert.equal(s.overlayState(viewB).counts.rose,0);
  assert.equal(s.overlayState(viewA).counts.like,undefined);
  s.disconnect(token);assert.equal(s.overlayState(viewA).counts.rose,0);s.close();
});
